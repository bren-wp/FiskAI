#!/usr/bin/env python3
"""Verify (or regenerate) both checked-in representations of the legal rule catalog."""
import argparse
import datetime
import hashlib
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = "https://narodne-novine.nn.hr/clanci/sluzbeni/2025_06_89_1233.html"


def iso_date(value):
    if not isinstance(value, str) or not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}", value):
        raise ValueError("Invalid effective date")
    return datetime.date.fromisoformat(value)


def render(data, source_bytes=None):
    if source_bytes is None:
        source_bytes = (json.dumps(data, indent=2) + "\n").encode("utf-8")
    digest = hashlib.sha256(source_bytes).hexdigest()
    if set(data) != {"source", "scope", "rules"} or data["scope"] != "STANDARD_DOMESTIC_B2B":
        raise ValueError("Unexpected legal catalog")
    if data["source"] != SOURCE:
        raise ValueError("Review change of statutory source")
    rules = data["rules"]
    if not isinstance(rules, list) or not rules:
        raise ValueError("Missing legal rules")
    versions = set()
    previous_until = None
    kt_rows, php_rows = [], []
    for row in rules:
        if set(row) != {"from", "until", "version", "vatIssue", "nonVatIssue"}:
            raise ValueError("Unexpected rule fields")
        start, end = iso_date(row["from"]), iso_date(row["until"])
        version = row["version"]
        if start.year < 2026 or end <= start or (previous_until is not None and start < previous_until):
            raise ValueError("Invalid, overlapping or unordered legal intervals")
        if not isinstance(version, str) or not re.fullmatch(rf"HR-F2-{start.year}-v[1-9][0-9]*", version) or version in versions:
            raise ValueError("Invalid or duplicate rule version")
        if type(row["vatIssue"]) is not bool or type(row["nonVatIssue"]) is not bool:
            raise ValueError("Invalid obligation")
        versions.add(version)
        previous_until = end
        vat, non = str(row["vatIssue"]).lower(), str(row["nonVatIssue"]).lower()
        kt_rows.append(f'        Rule("{start}", "{end}", "{version}", {vat}, {non}),')
        php_rows.append(f"    ['from'=>'{start}','until'=>'{end}','version'=>'{version}','vatIssue'=>{vat},'nonVatIssue'=>{non}],")
    kt = ("package hr.brendigo.fiskai\n\n"
          "// Generated by scripts/check-legal-catalog.py. Do not edit manually.\n"
          "internal object LegalRuleCatalog {\n"
          f'    const val CATALOG_SHA256 = "{digest}"\n'
          "    data class Rule(val from: String, val until: String, val version: String, val vatIssue: Boolean, val nonVatIssue: Boolean)\n"
          "    private val rules = listOf(\n" + "\n".join(kt_rows) + "\n    )\n"
          "    fun resolve(date: String): Rule? = rules.singleOrNull { date >= it.from && date < it.until }\n"
          "}\n")
    php = ("<?php\ndeclare(strict_types=1);\n"
           "// Generated by scripts/check-legal-catalog.py. Do not edit manually.\n"
           "return [\n" + "\n".join(php_rows) + "\n];\n")
    return {
        "app/src/main/java/hr/brendigo/fiskai/LegalRuleCatalog.kt": kt,
        "server/src/LegalRuleCatalog.php": php,
    }


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    raw = (ROOT / "server/contracts/legal-rules.json").read_bytes()
    data = json.loads(raw.decode("utf-8"))
    for path, expected in render(data, raw).items():
        target = ROOT / path
        if args.write:
            target.write_bytes(expected.encode("utf-8"))
        elif target.read_bytes() != expected.encode("utf-8"):
            raise SystemExit("Generated legal catalog differs: " + path)
    print("Legal catalog representations match")


if __name__ == "__main__":
    main()
