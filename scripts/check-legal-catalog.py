#!/usr/bin/env python3
"""Verify (or regenerate) both checked-in representations of the legal rule catalog."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    data = json.loads((ROOT / "server/contracts/legal-rules.json").read_text(encoding="utf-8"))
    if set(data) != {"source", "scope", "rules"} or data["scope"] != "STANDARD_DOMESTIC_B2B":
        raise ValueError("Unexpected legal catalog")
    if data["source"] != "https://narodne-novine.nn.hr/clanci/sluzbeni/2025_06_89_1233.html":
        raise ValueError("Review change of statutory source")
    rules = data["rules"]
    if not isinstance(rules, list) or not rules:
        raise ValueError("Missing legal rules")
    years = []
    kt_rows, php_rows = [], []
    for row in rules:
        if set(row) != {"year", "version", "vatIssue", "nonVatIssue"}:
            raise ValueError("Unexpected rule fields")
        year, version = row["year"], row["version"]
        if type(year) is not int or not 2026 <= year <= 9999 or not isinstance(version, str) or not re.fullmatch(rf"HR-F2-{year}-v[1-9][0-9]*", version):
            raise ValueError("Invalid rule version")
        if type(row["vatIssue"]) is not bool or type(row["nonVatIssue"]) is not bool:
            raise ValueError("Invalid obligation")
        years.append(year)
        vat, non = str(row["vatIssue"]).lower(), str(row["nonVatIssue"]).lower()
        kt_rows.append(f'        {year} to Rule("{version}", {vat}, {non}),')
        php_rows.append(f"    {year} => ['version'=>'{version}','vatIssue'=>{vat},'nonVatIssue'=>{non}],")
    if years != sorted(set(years)):
        raise ValueError("Duplicate or unordered years")
    kt = ("package hr.brendigo.fiskai\n\n"
          "// Generated by scripts/check-legal-catalog.py. Do not edit manually.\n"
          "internal object LegalRuleCatalog {\n"
          "    data class Rule(val version: String, val vatIssue: Boolean, val nonVatIssue: Boolean)\n"
          "    val rules = mapOf(\n" + "\n".join(kt_rows) + "\n    )\n}\n")
    php = ("<?php\ndeclare(strict_types=1);\n"
           "// Generated by scripts/check-legal-catalog.py. Do not edit manually.\n"
           "return [\n" + "\n".join(php_rows) + "\n];\n")
    for path, expected in {
        "app/src/main/java/hr/brendigo/fiskai/LegalRuleCatalog.kt": kt,
        "server/src/LegalRuleCatalog.php": php,
    }.items():
        target = ROOT / path
        if args.write:
            target.write_bytes(expected.encode("utf-8"))
        elif target.read_bytes() != expected.encode("utf-8"):
            raise SystemExit("Generated legal catalog differs: " + path)
    print("Legal catalog representations match")

if __name__ == "__main__":
    main()
